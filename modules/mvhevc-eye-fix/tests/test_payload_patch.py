#!/usr/bin/env python3
"""Offline proof of the on-device payload generation (no vendor binaries).

The module builds its patched libraries from the device's own stock files. This
test extracts make_payload() from module/service.sh and module/action.sh, checks
that the two copies did not drift, and runs them with the host shell against a
synthetic zero-filled fixture large enough to cover the patch offsets. It then
verifies the generated bytes, the regeneration of a tampered payload and the
fail-closed path for a wrong expectation.

Usage: python tests/test_payload_patch.py
"""
import hashlib
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULE = HERE.parent / 'module'

SF_STOCK = '8db37c90c458e92faad1f0a6160d53e769da9759c6db14fb2cfedbcec1727490'
AP_STOCK = 'a1d055498e9bc9b09850748944f0605c7fd9052eec2050f027fa4724b449b047'
SF_PATCHED = '4e51540d13f50d94f6c8deabae1137158af826cff29c56cd30ce4963a9ef1973'
AP_PATCHED = '017dc755311dfc9ff42d2501d4daa4c33ce92ec7d1d543c333a80c6f62d18ddd'

PATCHES = {
    'libstagefright.so': ((0x1bbb20 + 1, b'\x15'),),
    'libaplayer.so': ((0x233e18 + 1, b'\x15'), (0xf568c, bytes.fromhex('23008052'))),
}
FIXTURE_SIZE = max(offset + len(patch) for patches in PATCHES.values() for offset, patch in patches) + 64


def bash():
    if os.name == 'nt':
        git_bash = Path('C:/Program Files/Git/bin/bash.exe')
        if git_bash.is_file():
            return str(git_bash)
    found = shutil.which('bash')
    if not found:
        raise SystemExit('bash is required for this test')
    return found


def function_body(text, name):
    match = re.search(r'^%s\(\) \{\n(.*?)\n\}\n' % re.escape(name), text, re.M | re.S)
    if not match:
        raise SystemExit(f'{name}() not found')
    return f'{name}() {{\n{match.group(1)}\n}}\n'


def expected_fixture(name):
    blob = bytearray(FIXTURE_SIZE)
    for offset, patch in PATCHES[name]:
        blob[offset:offset + len(patch)] = patch
    return hashlib.sha256(bytes(blob)).hexdigest()


def run(work, body, src, name, want):
    harness = work / 'harness.sh'
    harness.write_text('#!/bin/sh\nset -u\n' + f'MODDIR="{work.as_posix()}"\n' + body
                       + f'\nmake_payload "{src.as_posix()}" "{name}" "{want}"\n',
                       encoding='utf-8', newline='\n')
    return subprocess.run([bash(), str(harness)], capture_output=True, text=True)


def main():
    service = (MODULE / 'service.sh').read_text('utf-8')
    action = (MODULE / 'action.sh').read_text('utf-8')
    body = function_body(service, 'make_payload')
    if body != function_body(action, 'make_payload'):
        raise SystemExit('make_payload() drifted between service.sh and action.sh')
    for script, text in (('service.sh', service), ('action.sh', action)):
        for pin in (SF_STOCK, AP_STOCK):
            if pin not in text:
                raise SystemExit(f'{script} is missing the stock pin {pin}')
    if f'SF_PATCHED={SF_PATCHED}' not in service or f'SF_PATCHED={SF_PATCHED}' not in action:
        raise SystemExit('the pinned patched hash for libstagefright.so is not wired into both scripts')
    if f'AP_PATCHED={AP_PATCHED}' not in service or f'AP_PATCHED={AP_PATCHED}' not in action:
        raise SystemExit('the pinned patched hash for libaplayer.so is not wired into both scripts')
    for offset, _ in sum(PATCHES.values(), ()):
        if str(offset) not in service:
            raise SystemExit(f'the decimal patch offset {offset} is not present in service.sh')

    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as directory:
        work = Path(directory)
        src = work / 'stock.so'
        with src.open('wb') as handle:
            handle.truncate(FIXTURE_SIZE)
        for name in PATCHES:
            want = expected_fixture(name)
            result = run(work, body, src, name, want)
            if result.returncode:
                raise SystemExit(f'{name}: generation failed: {result.stdout}{result.stderr}')
            payload = work / 'bin' / name
            if hashlib.sha256(payload.read_bytes()).hexdigest() != want:
                raise SystemExit(f'{name}: generated bytes do not match the documented patches')
            if list((work / 'bin').glob('*.gen')):
                raise SystemExit(f'{name}: leftover .gen file after a successful run')
            payload.write_bytes(b'corrupted')
            if run(work, body, src, name, want).returncode:
                raise SystemExit(f'{name}: a tampered payload was not regenerated')
            if hashlib.sha256(payload.read_bytes()).hexdigest() != want:
                raise SystemExit(f'{name}: regeneration did not restore the pinned result')
            if run(work, body, src, name, '0' * 64).returncode == 0:
                raise SystemExit(f'{name}: a wrong expectation was not rejected')
            if list((work / 'bin').glob('*.gen')):
                raise SystemExit(f'{name}: leftover .gen file after a rejected run')
    print('OK: make_payload() regenerates, verifies and fails closed (synthetic fixture, no vendor binaries)')


if __name__ == '__main__':
    main()
